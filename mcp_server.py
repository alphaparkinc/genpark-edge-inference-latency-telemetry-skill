import sys, json
from client import EdgeInferenceLatencyTelemetry

def handle_jsonrpc(line):
    try:
        req = json.loads(line)
        req_id = req.get("id")
        method = req.get("method")
        if method == "initialize":
            return {"jsonrpc": "2.0", "id": req_id, "result": {"protocolVersion": "2024-11-05", "serverInfo": {"name": "genpark-edge-inference-latency-telemetry-skill", "version": "1.0.0"}, "capabilities": {"tools": {}}}}
        elif method == "tools/list":
            return {"jsonrpc": "2.0", "id": req_id, "result": {"tools": [
                {"name": "profile_latency", "description": "Profile token generation timestamps.", "inputSchema": {"type": "object", "properties": {"timestamps_sec": {"type": "array"}}, "required": ["timestamps_sec"]}},
                {"name": "benchmark_telemetry", "description": "Run standard edge latency benchmark.", "inputSchema": {"type": "object", "properties": {}}}
            ]}}
        elif method == "tools/call":
            params = req.get("params", {})
            tool = params.get("name")
            args = params.get("arguments", {})
            if tool == "profile_latency":
                res = EdgeInferenceLatencyTelemetry.profile(args.get("timestamps_sec", []))
            elif tool == "benchmark_telemetry":
                res = EdgeInferenceLatencyTelemetry.benchmark_telemetry()
            else:
                return {"jsonrpc": "2.0", "id": req_id, "error": {"code": -32601, "message": "Method not found"}}
            return {"jsonrpc": "2.0", "id": req_id, "result": {"content": [{"type": "text", "text": json.dumps(res, indent=2)}]}}
        return {"jsonrpc": "2.0", "id": req_id, "result": {}}
    except Exception as e:
        return {"jsonrpc": "2.0", "id": None, "error": {"code": -32603, "message": str(e)}}

def main():
    for line in sys.stdin:
        if line.strip():
            print(json.dumps(handle_jsonrpc(line.strip())), flush=True)

if __name__ == "__main__":
    main()
